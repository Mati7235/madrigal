fn find(key: &str) -> Option<&'static (&'static str, &'static str, &'static str)> {
    ENTRIES
        .binary_search_by(|entry| entry.0.cmp(key))
        .ok()
        .map(|index| &ENTRIES[index])
}

pub fn contains(key: &str) -> bool {
    find(key).is_some()
}

pub fn len() -> usize {
    ENTRIES.len()
}

pub fn is_empty() -> bool {
    ENTRIES.is_empty()
}

pub fn keys() -> impl ExactSizeIterator<Item = &'static str> {
    ENTRIES.iter().map(|entry| entry.0)
}

pub fn try_tr(lang: Lang, key: &str) -> Result<&'static str, UnknownKey<'_>> {
    find(key)
        .map(|entry| match lang {
            Lang::Es => entry.1,
            Lang::En => entry.2,
        })
        .ok_or(UnknownKey(key))
}

pub fn tr(lang: Lang, key: &str) -> &str {
    try_tr(lang, key).unwrap_or(key)
}
