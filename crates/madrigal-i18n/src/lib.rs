fn find(key: &str) -> Option<&'static (&'static str, &'static str, &'static str)> {
    ENTRIES
        .binary_search_by(|entry| entry.0.cmp(key))
        .ok()
        .map(|index| &ENTRIES[index])
}

pub fn contains(key: &str) -> bool {
    find(key).is_some()
}

pub fn len() -> usize {
    ENTRIES.len()
}

pub fn is_empty() -> bool {
    ENTRIES.is_empty()
}

pub fn keys() -> impl ExactSizeIterator<Item = &'static str> {
    ENTRIES.iter().map(|entry| entry.0)
}

pub fn try_tr(lang: Lang, key: &str) -> Result<&'static str, UnknownKey<'_>> {
    find(key)
        .map(|entry| match lang {
            Lang::Es => entry.1,
            Lang::En => entry.2,
        })
        .ok_or(UnknownKey(key))
}

pub fn tr(lang: Lang, key: &str) -> &str {
    try_tr(lang, key).unwrap_or(key)
}

pub fn format(template: &str, args: &[&str]) -> String {
    let mut out = String::with_capacity(template.len());
    let mut rest = template;
    while let Some(at) = rest.find('%') {
        out.push_str(&rest[..at]);
        let after = &rest[at + 1..];
        let digits: String = after
            .chars()
            .take_while(|ch| ch.is_ascii_digit())
            .collect();
        let arg = digits
            .parse::<usize>()
            .ok()
            .filter(|index| *index > 0)
            .and_then(|index| args.get(index - 1));
        match arg {
            Some(arg) => {
                out.push_str(arg);
                rest = &after[digits.len()..];
            }
            None => {
                out.push('%');
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

pub fn trf(lang: Lang, key: &str, args: &[&str]) -> String {
    format(try_tr(lang, key).unwrap_or(key), args)
}
